/** Asignaturas ordenadas por rentabilidad (tier del chart) y, dentro del tier, nº de capítulos. */
export function asignaturasPorRentabilidad(): MirAsignatura[] {
  return [...MIR_TEMARIO].sort((a, b) => {
    const da = RENT_TIER[a.rentColor].orden, db = RENT_TIER[b.rentColor].orden;
    if (da !== db) return da - db;
    return b.chapters.length - a.chapters.length;
  });
}

